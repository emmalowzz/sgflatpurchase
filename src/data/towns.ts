export const FLAT_TYPES = [
  'ALL',
  '2 ROOM',
  '3 ROOM',
  '4 ROOM',
  '5 ROOM',
  'EXECUTIVE',
  'MULTI-GENERATION'
];

export function getTownProfile(townName: string): TownProfile | undefined {
  if (!townName || townName === 'ALL') return undefined;
  const upper = townName.toUpperCase().trim();
  return SINGAPORE_TOWNS.find(t => t.id === upper || t.name === upper);
}
